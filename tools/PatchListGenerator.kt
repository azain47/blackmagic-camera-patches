// Generates patches-list.json from the built bundle, in the schema the Morphe
// patch indexes read (same fields as the official morphe-patches-template output).
//
// Usage (see build.sh): java -cp <morphe-desktop-all.jar>:<this tool's jar>
//   PatchListGeneratorKt <bundle.mpp> <version> <output.json>

import app.morphe.patcher.patch.loadPatchesFromJar
import java.io.File

fun main(args: Array<String>) {
    require(args.size == 3) { "usage: PatchListGenerator <bundle.mpp> <version> <output.json>" }
    val (bundle, version, output) = args
    val patches = loadPatchesFromJar(setOf(File(bundle))).sortedBy { it.name }

    val list = patches.map { patch ->
        linkedMapOf(
            "name" to patch.name,
            "description" to patch.description,
            "default" to patch.default,
            "category" to patch.category,
            // null = universal patch (applies to any app)
            "compatiblePackages" to patch.compatibility?.map { compat ->
                linkedMapOf(
                    "packageName" to compat.packageName,
                    "name" to compat.name,
                    "description" to compat.description,
                    "apkFileType" to compat.apkFileType?.name,
                    "appIconColor" to compat.appIconColor?.let { "#%06X".format(it) },
                    "signatures" to compat.signatures?.toList(),
                    "formFactor" to compat.formFactor?.name,
                    "targets" to compat.targets.map { target ->
                        linkedMapOf(
                            "version" to target.version,
                            "versionCodes" to target.versionCodes?.mapKeys { it.key.name },
                            "isExperimental" to target.isExperimental,
                            "minSdk" to target.minSdk,
                            "description" to target.description,
                        )
                    },
                )
            },
            "options" to patch.options.values.map { option ->
                linkedMapOf(
                    "key" to option.key,
                    "title" to option.title,
                    "description" to option.description,
                    "required" to option.required,
                    "type" to option.type.toString(),
                    "default" to option.default,
                    "values" to option.values,
                )
            },
        )
    }

    val root = linkedMapOf(
        "NOTE" to "Do NOT manually edit this file. It is regenerated by build.sh from the built bundle.",
        "version" to version,
        "patches" to list,
    )
    File(output).writeText(toJson(root, 0) + "\n")
}

private fun toJson(value: Any?, indent: Int): String {
    val pad = "  ".repeat(indent + 1)
    val end = "  ".repeat(indent)
    return when (value) {
        null -> "null"
        is String -> quote(value)
        is Boolean, is Int, is Long, is Short, is Byte -> value.toString()
        is Number -> value.toString()
        is Map<*, *> ->
            if (value.isEmpty()) "{}"
            else value.entries.joinToString(",\n", "{\n", "\n$end}") { (k, v) ->
                "$pad${quote(k.toString())}: ${toJson(v, indent + 1)}"
            }
        is Iterable<*> ->
            if (!value.iterator().hasNext()) "[]"
            else value.joinToString(",\n", "[\n", "\n$end]") { "$pad${toJson(it, indent + 1)}" }
        is Array<*> -> toJson(value.toList(), indent)
        else -> quote(value.toString())
    }
}

private fun quote(s: String): String = buildString {
    append('"')
    for (c in s) when (c) {
        '"' -> append("\\\"")
        '\\' -> append("\\\\")
        '\n' -> append("\\n")
        '\r' -> append("\\r")
        '\t' -> append("\\t")
        else -> if (c < ' ') append("\\u%04x".format(c.code)) else append(c)
    }
    append('"')
}
